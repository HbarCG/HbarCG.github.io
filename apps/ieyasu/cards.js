//   flag: 'name' … 選んだことを印として残す。数年後の「続きの出来事」の条件に使う
//   text:  結果の文章
//
// ■ カードに書けるもの
//   scene: 場面の絵の名前（art.js の SCENES。castle / fire / ship など）
//   minYear: この年以降に出る / when: 出る条件（関数） / weight: 出やすさ（標準1）
//   maxYear: この年までしか出ない（時代の出来事に使う）
//   again: 2回目以降に出たときの書き出し（text のかわりに出る）。{last} は前回選んだ選択肢の文言になる
